-- ===========================================================================
-- STEP 1 -- wipe every table this touches. `swipe_decks cascade` also empties
-- swipe_deck_recipes and swipe_deck_shares (both FK to swipe_decks.id).
-- ===========================================================================
truncate table recipe_priority;
truncate table swipe_events;
truncate table swipe_decks cascade;
truncate table recipe_photos;
truncate table imported_recipes;
truncate table meal_calendar_entries;
truncate table recipe_tag_overrides;
truncate table recipe_overrides;
truncate table meal_plan_items;
