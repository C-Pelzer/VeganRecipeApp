-- ===========================================================================
-- STEP 2 -- drop every check constraint that hardcodes 'Cameron'/'Mallorie',
-- wherever it actually lives (not by guessing autogenerated names). Has to
-- happen before the column type changes below.
-- ===========================================================================
do $$
declare c record;
begin
  for c in
    select conname, conrelid::regclass as tbl
    from pg_constraint
    where contype = 'c' and pg_get_constraintdef(oid) ilike '%Cameron%'
  loop
    execute format('alter table %s drop constraint %I', c.tbl, c.conname);
  end loop;
end $$;

-- ===========================================================================
-- STEP 3 -- recipe_priority / swipe_events (scripts/schema-priority-favorites.sql)
-- ===========================================================================
alter table recipe_priority
  add column household_id uuid not null references households (id),
  alter column user_id type uuid using (user_id::uuid),
  add constraint recipe_priority_user_id_fkey foreign key (user_id) references profiles (id);

alter table swipe_events
  add column household_id uuid not null references households (id),
  alter column user_id type uuid using (user_id::uuid),
  add constraint swipe_events_user_id_fkey foreign key (user_id) references profiles (id);

drop policy "anon full access" on recipe_priority;
drop policy "anon full access" on swipe_events;
create policy "household members" on recipe_priority for all to authenticated
  using (household_id = current_household_id()) with check (household_id = current_household_id());
create policy "household members" on swipe_events for all to authenticated
  using (household_id = current_household_id()) with check (household_id = current_household_id());

-- apply_swipe's signature changes (p_user_id text -> uuid, new p_household_id).
drop function apply_swipe(text, text, text, text);
create or replace function apply_swipe(p_user_id uuid, p_recipe_id text, p_direction text, p_deck_id text, p_household_id uuid)
returns recipe_priority as $$
declare result recipe_priority;
begin
  insert into recipe_priority (user_id, recipe_id, household_id) values (p_user_id, p_recipe_id, p_household_id)
    on conflict (user_id, recipe_id) do nothing;

  if p_direction = 'right' then
    update recipe_priority set priority = priority + 1, favorited = true, updated_at = now()
      where user_id = p_user_id and recipe_id = p_recipe_id;
  elsif p_direction = 'left' then
    update recipe_priority set priority = priority - 1, updated_at = now()
      where user_id = p_user_id and recipe_id = p_recipe_id;
  else -- 'down'
    update recipe_priority set removed_at = now(), updated_at = now()
      where user_id = p_user_id and recipe_id = p_recipe_id;
  end if;

  update recipe_priority set removed_at = coalesce(removed_at, now())
    where user_id = p_user_id and recipe_id = p_recipe_id and priority <= 0;

  insert into swipe_events (user_id, recipe_id, direction, deck_id, household_id)
    values (p_user_id, p_recipe_id, p_direction, p_deck_id, p_household_id);

  select * into result from recipe_priority where user_id = p_user_id and recipe_id = p_recipe_id;
  return result;
end;
$$ language plpgsql;

grant execute on function apply_swipe(uuid, text, text, text, uuid) to authenticated;

-- ===========================================================================
-- STEP 4 -- swipe_decks / swipe_deck_recipes / swipe_deck_shares
-- (scripts/schema-swipe-decks.sql). Auto decks (source='auto', rebuilt
-- wholesale by build-swipe-decks.mjs from the shared recipe pool) stay
-- household_id NULL and readable by everyone -- they aren't household data.
-- Only manual decks are household-owned. swipe_deck_recipes/
-- swipe_deck_shares aren't given their own household_id column -- they're
-- scoped via a join back to swipe_decks, one source of truth for ownership.
-- ===========================================================================
alter table swipe_decks
  add column household_id uuid references households (id),
  add constraint swipe_decks_household_manual_check check (source = 'auto' or household_id is not null),
  alter column created_by drop not null,
  alter column created_by type uuid using (created_by::uuid),
  add constraint swipe_decks_created_by_fkey foreign key (created_by) references profiles (id);

alter table swipe_deck_shares
  alter column shared_with type uuid using (shared_with::uuid),
  alter column shared_by type uuid using (shared_by::uuid),
  add constraint swipe_deck_shares_shared_with_fkey foreign key (shared_with) references profiles (id),
  add constraint swipe_deck_shares_shared_by_fkey foreign key (shared_by) references profiles (id);

drop policy "anon full access" on swipe_decks;
drop policy "anon full access" on swipe_deck_recipes;
drop policy "anon full access" on swipe_deck_shares;

create policy "auto decks readable, manual decks household-owned" on swipe_decks for all to authenticated
  using (source = 'auto' or household_id = current_household_id())
  with check (source = 'auto' or household_id = current_household_id());

create policy "scoped via parent deck" on swipe_deck_recipes for all to authenticated
  using (exists (
    select 1 from swipe_decks d where d.id = deck_id
      and (d.source = 'auto' or d.household_id = current_household_id())
  ))
  with check (exists (
    select 1 from swipe_decks d where d.id = deck_id
      and (d.source = 'auto' or d.household_id = current_household_id())
  ));

create policy "scoped via parent deck" on swipe_deck_shares for all to authenticated
  using (exists (select 1 from swipe_decks d where d.id = deck_id and d.household_id = current_household_id()))
  with check (exists (select 1 from swipe_decks d where d.id = deck_id and d.household_id = current_household_id()));

-- scripts/build-swipe-decks.mjs runs as a batch script with the anon key and
-- no signed-in session (there's no service-role key in this project's
-- convention) -- it needs its own policy to keep rebuilding the global auto
-- decks, scoped strictly to source='auto' so it can never touch a
-- household's manual decks.
create policy "anon manages auto decks" on swipe_decks for all to anon
  using (source = 'auto') with check (source = 'auto');
create policy "anon manages auto deck recipes" on swipe_deck_recipes for all to anon
  using (exists (select 1 from swipe_decks d where d.id = deck_id and d.source = 'auto'))
  with check (exists (select 1 from swipe_decks d where d.id = deck_id and d.source = 'auto'));

