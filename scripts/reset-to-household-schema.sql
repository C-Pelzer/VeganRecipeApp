-- Run this in the Supabase SQL editor, once, after scripts/schema-auth.sql.
-- This is a DESTRUCTIVE RESET, not a data-preserving migration: every row in
-- the tables below is wiped rather than mapped onto real accounts. That's a
-- deliberate choice (starting the first household fresh via normal sign-up
-- instead of migrating Cameron/Mallorie's existing swipes, favorites, decks,
-- meal plan, shopping list, imported recipes, and photos) — reconsider before
-- running this if that's not what you want anymore.
--
-- Because nothing is preserved, this does NOT need anyone to have signed in
-- first, and does NOT need your email addresses filled in anywhere — unlike
-- a real migration, there's no old text data to map onto new profile ids.
-- Sign-up and the first household are created entirely through the normal
-- app flow (SignInScreen -> HouseholdOnboardingScreen) after this runs.
--
-- Still recommended: export/back up the tables below first (Table Editor ->
-- export) in case "start fresh" turns out to mean "we wanted last week's
-- favorites back" — cheap insurance, not required.

